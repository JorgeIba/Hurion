package workflow

import (
	"encoding/json"
	"os"
	"path/filepath"
	"testing"
	"time"

	"github.com/JorgeIba/Hurion/app/data"
	"github.com/JorgeIba/Hurion/app/infrastructure/storage"
	"github.com/JorgeIba/Hurion/app/presentation/jsonexport"
	"github.com/JorgeIba/Hurion/app/workers"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestScoreboardExportOnDbHook(t *testing.T) {
	env := setupWorkflowEnv(t)
	tempExportDir := t.TempDir()

	// Instantiate DiskStorage and Worker with new layered architecture
	diskStore, err := storage.NewDiskStorage(tempExportDir)
	require.NoError(t, err)
	worker := workers.NewScoreboardExporterWorker(env.Services.Class, env.Services.Score, diskStore)
	worker.DebounceDuration = 50 * time.Millisecond
	worker.Start()
	defer worker.Stop()

	// Register update hook to trigger background export
	data.RegisterUpdateHookCallback(func(op int, dbName string, tableName string, rowid int64) {
		if tableName == "solved_problems" {
			worker.Trigger()
		}
	})

	// Seed test data
	classCode := "basicos_hook_test"
	className := "Basicos Hook Test Class"
	classID := env.seedClass(t, classCode, className)

	probName := "Two Sum"
	probURL := "https://leetcode.com/problems/two-sum"
	probDifficulty := "easy"
	probTopic := "Arrays"
	probID := env.seedProblem(t, probName, probURL, classID, probDifficulty, probTopic)

	userID := "user_123"
	userDisplayName := "Alice Tester"
	env.seedUser(t, userID, userDisplayName)

	// Verify no scoreboard JSON file exists yet
	expectedFile := filepath.Join(tempExportDir, classCode+"_score.json")
	_, statErr := os.Stat(expectedFile)
	assert.True(t, os.IsNotExist(statErr), "Expected JSON file not to exist yet")

	// Trigger database write to solved_problems (which triggers the hook)
	err = env.DB.AddAC(userID, probID)
	require.NoError(t, err)

	// Wait up to 1 second for the debounced background export worker to execute
	var fileExists bool
	for i := 0; i < 20; i++ {
		time.Sleep(50 * time.Millisecond)
		if _, err := os.Stat(expectedFile); err == nil {
			fileExists = true
			break
		}
	}

	require.True(t, fileExists, "Expected scoreboard JSON file to be generated by background worker hook")

	// Read and validate the generated JSON file
	fileBytes, err := os.ReadFile(expectedFile)
	require.NoError(t, err)

	var scoreboard jsonexport.ScoreboardJSON
	err = json.Unmarshal(fileBytes, &scoreboard)
	require.NoError(t, err)

	// Assert correct class metadata
	assert.Equal(t, classCode, scoreboard.ClassCode)
	assert.Equal(t, className, scoreboard.ClassName)

	// Assert correct problem mapping
	require.Len(t, scoreboard.Problems, 1)
	assert.Equal(t, probID, scoreboard.Problems[0].ID)
	assert.Equal(t, probName, scoreboard.Problems[0].Name)
	assert.Equal(t, probURL, scoreboard.Problems[0].URL)
	assert.Equal(t, &probDifficulty, scoreboard.Problems[0].Difficulty)
	assert.Equal(t, probTopic, scoreboard.Problems[0].Topic)

	// Assert correct user mapping and solve list
	require.Len(t, scoreboard.Users, 1)
	assert.Equal(t, userID, scoreboard.Users[0].UserID)
	assert.Equal(t, userDisplayName, scoreboard.Users[0].DisplayName)
	assert.Equal(t, 1, scoreboard.Users[0].SolvedCount)
	require.Len(t, scoreboard.Users[0].Solved, 1)
	assert.Equal(t, probID, scoreboard.Users[0].Solved[0])
}
